# Generate src/rdna2_ops.h from AMD's RDNA2 ISA spec:
#   #define OP_<ENC>_<NAME> <opcode>   for every instruction in every base encoding
#   static const char* const rdna2_names_<ENC>[512]   opcode -> name (for error messages)
#   static const unsigned char rdna2_lit_<ENC>[512]    1 if the opcode always carries a trailing literal
# usage: gen_ops.py <amdgpu_isa_rdna2.xml> <out.h>
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rdna2dis

spec = rdna2dis.load_spec(sys.argv[1])
out = ["/* generated by tools/gen_ops.py from AMD's machine-readable RDNA2 ISA spec - do not edit */", "#pragma once", ""]
for enc in rdna2dis.BASE_ENCODINGS:
    ops = spec["ops"].get(enc, {})
    short = enc.replace("ENC_", "")
    for opc in sorted(ops):
        nm = ops[opc][0]
        out.append("#define OP_%s_%s %d" % (short, nm, opc))
    out.append("static const char* const rdna2_names_%s[512] = {" % short)
    out.append("    " + ", ".join('[%d] = "%s"' % (opc, ops[opc][0]) for opc in sorted(ops) if opc < 512))
    out.append("};")
    lits = [opc for opc in sorted(ops) if ops[opc][2] and opc < 512]
    out.append("static const unsigned char rdna2_lit_%s[512] = { %s };" % (short, ", ".join("[%d] = 1" % o for o in lits) if lits else "0"))
    out.append("")
open(sys.argv[2], "w", newline="\n").write("\n".join(out) + "\n")
print("wrote", sys.argv[2], sum(len(v) for v in spec["ops"].values()), "opcodes")
